    def test_uncommitted_content_and_other_private_tags_are_never_exported(self):
        expected = self.git(self.source, "rev-parse", "v0.5.2^{tree}").strip().decode()
        self.write("README.md", b"PRIVATE UNCOMMITTED CONTENT")
        self.write(".env", b"PRIVATE LOCAL OUTPUT")
        self.git(self.source, "tag", "private-do-not-push", self.private_commit)
        with self.plan() as plan:
            self.assertEqual(plan.tree, expected)
            plan.publish()
        refs = self.git(self.public, "for-each-ref", "--format=%(refname)").decode().splitlines()
        self.assertEqual(sorted(refs), ["refs/heads/main", "refs/tags/v0.5.2"])

    def test_concurrent_public_change_before_push_stops(self):
        with self.plan() as plan:
            other = self.advance_public()
            with self.assertRaises(bridge.BridgeError):
                plan.publish()
        self.assertEqual(self.ref("main"), other)
        self.assertFalse(self.tag_exists())

    def advance_public(self):
        tree = self.git(self.public, "rev-parse", "main^{tree}").strip().decode()
        commit = self.git(self.public, "commit-tree", tree, "-p", self.ref("main"), data=b"Concurrent public change\n").strip().decode()
        self.git(self.public, "update-ref", "refs/heads/main", commit)
        return commit

    def test_atomic_non_fast_forward_race_creates_neither_partial_tag_nor_overwrite(self):
        original = bridge.run_git
        other = []

        def race(repo, *args, **kwargs):
            if "push" in args:
                self.assertIn("--atomic", args)
                self.assertFalse(any(arg.startswith("+") or arg in ("--force", "--mirror", "--tags", "--delete") for arg in args))
                other.append(self.advance_public())
            return original(repo, *args, **kwargs)

        with self.plan() as plan, mock.patch.object(bridge, "run_git", side_effect=race):
            with self.assertRaises(bridge.BridgeError):
                plan.publish()
        self.assertEqual(self.ref("main"), other[0])
        self.assertFalse(self.tag_exists())

